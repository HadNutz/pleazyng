#!/usr/bin/env python3
"""Generate codec identities from a reviewed FFmpeg source checkout.

This is a naming catalogue, never a support allowlist. Runtime enumeration
must independently establish the decoder's presence in the installed engine.
"""
import argparse
import hashlib
import re
import subprocess
from pathlib import Path


def names(source):
    groups = {kind: set() for kind in ('VIDEO', 'AUDIO', 'SUBTITLE')}
    for block in re.findall(r'\{\s*\.id\s*=\s*AV_CODEC_ID_.*?\n    \}', source, re.S):
        kind = re.search(r'\.type\s*=\s*AVMEDIA_TYPE_(\w+)', block)
        name = re.search(r'\.name\s*=\s*"([a-zA-Z0-9_+.-]+)"', block)
        if kind and name and kind[1] in groups:
            groups[kind[1]].add(name[1])
    if any(len(group) < minimum for group, minimum in zip(groups.values(), (200, 150, 15))):
        raise ValueError('Unexpected or incomplete FFmpeg descriptor source')
    return groups


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('ffmpeg', type=Path)
    parser.add_argument('--commit', required=True)
    parser.add_argument('--output', type=Path, default=Path('lib/media/ffmpeg_codec_names.dart'))
    args = parser.parse_args()
    actual = subprocess.check_output(['git', '-C', str(args.ffmpeg), 'rev-parse', 'HEAD'], text=True).strip()
    if actual != args.commit:
        raise SystemExit('Source commit does not match the reviewed pin')
    source_path = 'libavcodec/codec_desc.c'
    data = subprocess.check_output(['git', '-C', str(args.ffmpeg), 'show', f'{actual}:{source_path}'])
    groups = names(data.decode('utf-8'))
    lines = ['// Generated by scripts/generate_codec_names.py; identities, not support claims.',
             f'// https://github.com/FFmpeg/FFmpeg/blob/{actual}/{source_path}',
             f'// Source SHA-256: {hashlib.sha256(data).hexdigest()}', '',
             'abstract final class FfmpegCodecNames {']
    for kind, values in groups.items():
        lines += [f'  static const {kind.lower()} = <String>{{']
        lines += [f"    '{name}'," for name in sorted(values)]
        lines += ['  };']
    lines += ['}', '']
    args.output.write_text('\n'.join(lines))
    print(', '.join(f'{key.lower()}={len(value)}' for key, value in groups.items()))


if __name__ == '__main__':
    main()
